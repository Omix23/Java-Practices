package ObjectOrientedProgramming.Abstraction;

interface Interface {
    // An interface is purely abstract body.
    // By default all methods in an interface are public and abstract.
    // By default Data(Variable) is public,final and static.
    // implements keyword is used by class to implement the interface.
    // Multiple inheritance can be applied using interface.
    // a class can extends another class and implement multiple interfaces.
    // EX - class A extends B implements Interface1,Interface2,Interface3. Separated by ( , ).
    // empty interface is called as marker interface
    // interface  with single method is called as Functional Interface.

}
